#!/usr/bin/env python3
"""Refresh js/podcast-data.js with the latest episodes from The IX Podcast's YouTube channel.

YouTube's public RSS feed isn't available for this channel, so this reads the channel's Videos page
(the same data a browser gets) and keeps each video's ID and title. Runs every morning from
.github/workflows/update-news.yml; it leaves the file unchanged if YouTube can't be reached.
"""
import datetime as dt
import json
import pathlib
import re
import sys
import urllib.request

CHANNEL_URL = "https://www.youtube.com/@theixpodcast"
OUT = pathlib.Path(__file__).resolve().parent.parent / "js" / "podcast-data.js"
MAX_EPISODES = 12


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (The Tip-Off podcast updater)", "Accept-Language": "en-US,en"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def texts(o, acc):
    if isinstance(o, dict):
        if isinstance(o.get("content"), str):
            acc.append(o["content"])
        for v in o.values():
            texts(v, acc)
    elif isinstance(o, list):
        for v in o:
            texts(v, acc)
    return acc


def episodes_from(page):
    m = re.search(r"var ytInitialData = (\{.*?\});</script>", page, re.S)
    if not m:
        return []
    data = json.loads(m.group(1))
    out, seen = [], set()

    def walk(o):
        if isinstance(o, dict):
            if "lockupViewModel" in o:
                l = o["lockupViewModel"]
                vid = l.get("contentId")
                title = l.get("metadata", {}).get("lockupMetadataViewModel", {}).get("title", {}).get("content", "")
                if vid and title and vid not in seen and re.fullmatch(r"[A-Za-z0-9_-]{11}", vid):
                    seen.add(vid)
                    out.append({"id": vid, "title": title.strip()})
            elif "videoRenderer" in o:  # older page layout
                v = o["videoRenderer"]
                vid = v.get("videoId")
                title = "".join(r.get("text", "") for r in v.get("title", {}).get("runs", []))
                if vid and title and vid not in seen:
                    seen.add(vid)
                    out.append({"id": vid, "title": title.strip()})
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(data)
    return out[:MAX_EPISODES]


def main():
    try:
        eps = episodes_from(fetch(CHANNEL_URL + "/videos"))
    except Exception as e:  # network trouble: keep yesterday's file
        print("Could not reach YouTube:", e)
        return 0
    if not eps:
        print("No episodes found; leaving the file as it is.")
        return 0
    old = OUT.read_text() if OUT.exists() else ""
    if all(e["id"] in old for e in eps[:3]) and len(re.findall(r'"id":', old)) == len(eps):
        print("Episodes unchanged.")
        return 0
    payload = {
        "updated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "channel": CHANNEL_URL,
        "episodes": eps,
    }
    OUT.write_text("/* Generated by scripts/update_podcast.py — do not edit by hand. */\nconst SITE_PODCAST = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    print(f"Saved {len(eps)} episodes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
