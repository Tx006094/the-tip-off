"""Regenerate js/teams-data.js from ESPN's team and conference lists (their endpoints don't allow browser requests).
Run: python3 scripts/update_teams.py
"""
import datetime as dt
import gzip
import json
import pathlib
import urllib.request

BASE = "https://site.api.espn.com/apis/site/v2/sports/basketball"
CORE = "https://sports.core.api.espn.com/v2/sports/basketball/leagues/womens-college-basketball"


def get(url):
    req = urllib.request.Request(url.replace("http://", "https://"), headers={"Accept-Encoding": "gzip"})
    raw = urllib.request.urlopen(req, timeout=30).read()
    try:
        raw = gzip.decompress(raw)
    except OSError:
        pass
    return json.loads(raw)


out = {}
for lg, slug in [("wnba", "wnba"), ("ncaa", "womens-college-basketball")]:
    teams = get(f"{BASE}/{slug}/teams?limit=500")["sports"][0]["leagues"][0]["teams"]
    out[lg] = [
        {"id": t["id"], "name": t["displayName"], "short": t.get("shortDisplayName"),
         "abbr": t.get("abbreviation"), "logo": (t.get("logos") or [{}])[0].get("href", ""), "color": t.get("color")}
        for t in (x["team"] for x in teams)
    ]

# Division I conferences (ESPN group 50), for the schedule's conference filter. Game data already names
# each team's conference by id, so only the names are needed here. A season is named for the year it ends.
today = dt.date.today()
season = today.year + 1 if today.month >= 8 else today.year
LABELS = {"10": "CAA", "46": "ASUN", "14": "MAC"}  # where ESPN's mid-length name is less familiar than the acronym
conferences = []
for item in get(f"{CORE}/seasons/{season}/types/2/groups/50/children?limit=60")["items"]:
    g = get(item["$ref"])
    conferences.append({"id": g["id"], "name": g["name"], "label": LABELS.get(g["id"]) or g.get("midsizeName") or g.get("shortName") or g["name"]})
conferences.sort(key=lambda c: c["label"].lower())

dest = pathlib.Path(__file__).resolve().parent.parent / "js" / "teams-data.js"
dest.write_text("/* Generated by scripts/update_teams.py — do not edit by hand. */\n"
                "const ESPN_TEAMS = " + json.dumps(out, separators=(",", ":")) + ";\n"
                "const ESPN_CONFERENCES = " + json.dumps(conferences, separators=(",", ":")) + ";\n")
print({k: len(v) for k, v in out.items()}, len(conferences), "conferences ->", dest)
