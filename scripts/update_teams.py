"""Regenerate js/teams-data.js from ESPN's team lists (their teams endpoint doesn't allow browser requests).
Run: python3 scripts/update_teams.py
"""
import json, urllib.request, gzip, pathlib

BASE = "https://site.api.espn.com/apis/site/v2/sports/basketball"
out = {}
for lg, slug in [("wnba", "wnba"), ("ncaa", "womens-college-basketball")]:
    req = urllib.request.Request(f"{BASE}/{slug}/teams?limit=500", headers={"Accept-Encoding": "gzip"})
    raw = urllib.request.urlopen(req, timeout=30).read()
    try:
        raw = gzip.decompress(raw)
    except OSError:
        pass
    teams = json.loads(raw)["sports"][0]["leagues"][0]["teams"]
    out[lg] = [
        {"id": t["id"], "name": t["displayName"], "short": t.get("shortDisplayName"),
         "abbr": t.get("abbreviation"), "logo": (t.get("logos") or [{}])[0].get("href", ""), "color": t.get("color")}
        for t in (x["team"] for x in teams)
    ]
dest = pathlib.Path(__file__).resolve().parent.parent / "js" / "teams-data.js"
dest.write_text("/* Generated by scripts/update_teams.py — do not edit by hand. */\nconst ESPN_TEAMS = "
                + json.dumps(out, separators=(",", ":")) + ";\n")
print({k: len(v) for k, v in out.items()}, "->", dest)
