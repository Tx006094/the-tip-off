"""Pick the "Players to Watch" each morning and save them to js/players-data.js.

Reads ESPN's public scoreboards for the last 14 days (WNBA and NCAA Division I women's basketball).
Each finished game lists every team's top scorer; a player who led her team at least twice in that
window is a candidate. Players are ranked by their average over their last three of those games,
with a note for scoring streaks (20+ points in 3 straight) and big nights (30+).

The site itself finds each player's next game and where to watch it, so the list stays useful all day.
If ESPN can't be reached, the previous list is kept. Run by hand any time:

    python3 scripts/update_players.py
"""
import datetime as dt
import json
import pathlib
import urllib.request

LEAGUES = [
    ("ncaa", "womens-college-basketball", "&groups=50&limit=300"),
    ("wnba", "wnba", ""),
]
DAYS = 14
KEEP = 16
UA = {"User-Agent": "TheTipOff-players/1.0 (personal, non-commercial)"}
DEST = pathlib.Path(__file__).resolve().parent.parent / "js" / "players-data.js"


def get(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.load(r)


def main():
    today = dt.datetime.now(dt.timezone.utc).date()
    players, reached = {}, 0
    for lg, sport, extra in LEAGUES:
        for i in range(1, DAYS + 1):
            day = (today - dt.timedelta(days=i)).strftime("%Y%m%d")
            try:
                data = get(f"https://site.api.espn.com/apis/site/v2/sports/basketball/{sport}/scoreboard?dates={day}{extra}")
                reached += 1
            except Exception:
                continue
            for ev in data.get("events", []):
                comp = ev["competitions"][0]
                if not comp["status"]["type"].get("completed"):
                    continue
                teams = comp["competitors"]
                for t in teams:
                    other = next(o for o in teams if o is not t)
                    pts = next((l for l in t.get("leaders", []) if l.get("name") == "points"), None)
                    if not pts or not pts.get("leaders"):
                        continue
                    top = pts["leaders"][0]
                    a = top["athlete"]
                    p = players.setdefault(a["id"], {
                        "id": a["id"], "name": a.get("displayName", ""), "short": a.get("shortName", ""),
                        "shot": a.get("headshot", ""), "pos": (a.get("position") or {}).get("abbreviation", ""),
                        "team": f'{lg}:{t["team"]["id"]}', "games": [],
                    })
                    p["games"].append({
                        "date": ev["date"][:10], "pts": int(top.get("value", 0)),
                        "opp": other["team"].get("shortDisplayName") or other["team"].get("displayName", ""),
                        "won": bool(t.get("winner")),
                    })
    if not reached:
        print("Could not reach ESPN; keeping the previous list.")
        return 0

    out = []
    for p in players.values():
        if len(p["games"]) < 2 or not p["shot"]:
            continue
        g = sorted(p["games"], key=lambda x: x["date"], reverse=True)
        last = g[:3]
        avg = sum(x["pts"] for x in last) / len(last)
        streak = 0
        for x in g:
            if x["pts"] >= 20:
                streak += 1
            else:
                break
        best = max(x["pts"] for x in g)
        if streak >= 3:
            tag, why = "On a streak", f"{streak} straight 20-point games"
        elif best >= 30:
            tag, why = "Big night", f"{best} points in a game this week" if (today - dt.date.fromisoformat(next(x["date"] for x in g if x["pts"] == best))).days <= 7 else f"{best} points in a recent game"
        else:
            tag, why = "Hot hand", f"{avg:.1f} points a game lately"
        out.append({k: p[k] for k in ("id", "name", "short", "shot", "pos", "team")} | {
            "avg": round(avg, 1), "last": len(last), "streak": streak, "best": best, "tag": tag, "why": why,
            "score": avg + streak * 2 + (3 if best >= 30 else 0),
        })
    out.sort(key=lambda x: x["score"], reverse=True)
    out = out[:KEEP]
    for x in out:
        x.pop("score")

    payload = {"updated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"), "players": out}
    text = ("/* Generated by scripts/update_players.py — do not edit by hand. */\n"
            "const PLAYERS = " + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n")
    if DEST.exists() and DEST.read_text(encoding="utf-8").split("\n", 3)[-1] == text.split("\n", 3)[-1]:
        print("No change.")
        return 0
    DEST.write_text(text, encoding="utf-8")
    print(f"Saved {len(out)} players.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
